/** 农历传统节日 (月名 + 日名) */
export function getLunarFestivalName(monthLabel: string, dayLabel: string): string | null {
  const cleanMonth = monthLabel.replace("闰", "");
  if (cleanMonth === "正月" && dayLabel === "初一") return "春节";
  if (cleanMonth === "正月" && dayLabel === "十五") return "元宵节";
  if (cleanMonth === "二月" && dayLabel === "二日") return "龙抬头";
  if (cleanMonth === "五月" && dayLabel === "初五") return "端午节";
  if (cleanMonth === "七月" && dayLabel === "初七") return "七夕节";
  if (cleanMonth === "七月" && dayLabel === "十五") return "中元节";
  if (cleanMonth === "八月" && dayLabel === "十五") return "中秋节";
  if (cleanMonth === "九月" && dayLabel === "初九") return "重阳节";
  if (cleanMonth === "腊月" && dayLabel === "初八") return "腊八节";
  if (cleanMonth === "腊月" && (dayLabel === "廿三" || dayLabel === "廿四")) return "小年";
  if (cleanMonth === "腊月" && (dayLabel === "三十" || dayLabel === "廿九")) return "除夕";
  return null;
}

/** 获取指定 ISO 日期 (YYYY-MM-DD) 的节假日与调休标注信息 */
export function getDayHolidayInfo(iso: string, lunarInfo?: { monthLabel: string; dayLabel: string } | null): DayHolidayInfo {
  const official = OFFICIAL_SCHEDULE[iso];
  const mmdd = iso.slice(5);

  let name: string | undefined = official?.name;

  // 1. 如果官方调休有自定义名字，优先使用
  // 2. 否则查找农历传统节日
  if (!name && lunarInfo) {
    const lunarFest = getLunarFestivalName(lunarInfo.monthLabel, lunarInfo.dayLabel);
    if (lunarFest) name = lunarFest;
  }

  // 3. 否则查找二十四节气
  if (!name && SOLAR_TERMS_REF[iso]) {
    name = SOLAR_TERMS_REF[iso];
  }

  // 4. 否则查找公历固定节日
  if (!name && FIXED_SOLAR_FESTIVALS[mmdd]) {
    name = FIXED_SOLAR_FESTIVALS[mmdd];
  }

  return {
    badge: official?.badge,
    name,
    isHoliday: official?.badge === "休",
  };
}
